# ─── 参数解析 ────────────────────────────────────────────
_VERB_RE = re.compile(
    r"^\s*(?:@\S+\s*)?(?:请|帮我|麻烦|给我|替我)?"
    r"(?:写|生成|起草|拟|做|出|搞|来|整|编制|制定|拟写|撰写|列一份|列个|搞一份)?"
    r"(?:一?(?:份|个|篇|套))?\s*"
)
_TRAIL_RE = re.compile(
    r"(?:的)?(?:培训方案|实施方案|工作计划|工作总结|课程大纲|写作大纲|大纲|会议纪要|通知|调研报告|汇报稿|讲话稿|工作清单|台账|方案|计划|总结|报告|文稿|材料)\s*$"
)


def parse_args(text, base=None):
    """从自然语言或 key=value 串里提取字段；不做任何联网/模型调用。"""
    ctx = dict(base or {})
    ctx.setdefault("date", date.today().strftime("%Y 年 %m 月 %d 日"))
    s = str(text or "").strip()

    for k, v in re.findall(r"([\u4e00-\u9fa5A-Za-z_]{1,10})\s*[=:：]\s*([^\s,，;；]+)", s):
        key = FIELD_ALIASES.get(k, k if k in FIELD_KEYS else None)
        if key:
            ctx[key] = v
    # 去掉显式 kv 片段，剩下的当作主题
    rest = re.sub(r"[\u4e00-\u9fa5A-Za-z_]{1,10}\s*[=:：]\s*[^\s,，;；]+", " ", s)
    # 去掉「，导出为 HTML」「，另存 PDF」这类输出格式子句，避免混进标题
    rest = re.sub(r"[，,、;；]\s*[^，,。;；]*(?:导出|另存|输出|保存|生成)[^，,。;；]*", " ", rest)
    rest = _VERB_RE.sub("", rest)
    # 去掉无逗号分隔的「导出为 HTML」「另存 PDF」等输出格式说明
    rest = re.sub(
        r"\s*(?:并|再|然后)?(?:导出|另存|输出|保存)(?:为|成)?\s*"
        r"(?:HTML|PDF|Word|Excel|PPT|Markdown|CSV|TXT|docx|pdf|html|xlsx|pptx|md|txt|csv|"
        r"网页|纯文本|幻灯片|演示文稿)(?=\s|$|[，,。;；])",
        " ", rest, flags=re.I)
    # 不再剥离主题里的「方案 / 总结 / 纪要」等词：那是主题本身的一部分，
    # 与模板标题拼接后产生的重复词由 _dedupe() 统一处理。
    rest = re.sub(r"\s*(?:关于|有关|针对|围绕)\s*", "", rest)
    rest = re.sub(r"\s+", " ", rest).strip(" ，,。.、；;：:的")
    rest = re.sub(r"^[，,、;；\s]+|[，,、;；\s]+$", "", rest)
    if rest and not (ctx.get("topic") and ctx.get("topic") in rest):
        ctx["topic"] = rest
    for k, _, _ in FIELDS:
        if k in ctx and ctx[k] is None:
            ctx[k] = ""
    return ctx


def _dedupe(title):
    """去掉主题与模板后缀撞词产生的重复，如「家政服务技能培训培训方案」。"""
    s = str(title or "")
    for _ in range(3):
        s2 = re.sub(r"([\u4e00-\u9fa5]{2,4})\1", r"\1", s)
        if s2 == s:
            break
        s = s2
    return s


def meta_line(meta, keys=("org", "dept", "period", "date")):
    """元信息行用中文字段名，不暴露内部英文键。"""
    return "　".join("%s：%s" % (FIELD_LABELS.get(k, k), v)
                    for k, v in (meta or {}).items() if v and k in keys)


def list_templates():
    return [{"id": t["id"], "label": t["label"], "cat": t["cat"],
             "desc": t["desc"], "sections": len(t["sections"])} for t in TEMPLATES]


